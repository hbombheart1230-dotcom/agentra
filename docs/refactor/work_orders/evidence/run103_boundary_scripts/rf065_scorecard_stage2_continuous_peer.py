# RF-065 P1 independent peer (A for B-owned RF): scripts/research/run_agent_effectiveness_scorecard.py as a REAL subprocess CLI
# (scorecard writer -> Stage2 writer, real writers, no fakes) on a synthetic tmp reports root. Partial failures are produced by REAL OS errors
# (a directory occupying an output file name -> IsADirectoryError), not by monkeypatching. The child process blocks network/subprocess/sqlite via a
# bootstrap and reports attempts. Usage: python rf065_scorecard_stage2_continuous_peer.py <repo_root> [-O]
import os, sys, json, re, shutil, subprocess, tempfile
from pathlib import Path
repo = Path(sys.argv[1]).resolve(); opt = ["-O"] if "-O" in sys.argv[2:] else []
def check(c, m):
    if not c: raise SystemExit("CHECK_FAILED: " + str(m))
SCHEMA = re.search(r'SCHEMA_VERSION = "([^"]+)"', (repo / "libs/reporting/evaluation/stage2_authority/contracts.py").read_text(encoding="utf-8")).group(1)
cli = repo / "scripts/research/run_agent_effectiveness_scorecard.py"
BOOT = r'''
import sys, os, socket, subprocess, sqlite3, atexit, runpy
bad = []
def blocked(n):
    def f(*a, **k): bad.append(n); raise OSError("blocked " + n)
    return f
socket.socket.connect = blocked("connect"); socket.create_connection = blocked("cc"); socket.getaddrinfo = blocked("gai")
for n in ("Popen", "run", "call", "check_call", "check_output"): setattr(subprocess, n, blocked(n))
os.system = blocked("os.system"); sqlite3.connect = blocked("sqlite")
atexit.register(lambda: sys.stderr.write("\nBLOCKED_ATTEMPTS=%d\n" % len(bad)))
script = sys.argv[1]; sys.argv = [script] + sys.argv[2:]
runpy.run_path(script, run_name="__main__")
'''
tmp = Path(tempfile.mkdtemp(prefix="rf065_sc_")).resolve()
def before_repo():
    r = subprocess.run(["git", "-C", str(repo), "status", "--porcelain"], capture_output=True, text=True); return r.stdout
repo_before = before_repo()
env = {k: v for k, v in os.environ.items() if not any(s in k.upper() for s in ("KIWOOM", "OPENROUTER", "API_KEY", "SECRET", "TOKEN", "ACCOUNT", "ALLOW_REAL", "PROXY"))}
env.update({"PYTHONDONTWRITEBYTECODE": "1", "PYTHONPATH": ""})
def put(p, obj): p.parent.mkdir(parents=True, exist_ok=True); p.write_text(json.dumps(obj), encoding="utf-8")
def files(root): return sorted(str(p.relative_to(root).as_posix()) for p in Path(root).rglob("*") if p.is_file())
def run(case, argv, cwd):
    r = subprocess.run([sys.executable, *opt, "-c", BOOT, str(cli), *argv], cwd=str(cwd), env=env, capture_output=True, text=True, timeout=120)
    err = r.stderr
    attempts = int(re.search(r"BLOCKED_ATTEMPTS=(\d+)", err).group(1)) if "BLOCKED_ATTEMPTS" in err else -1
    last = [l for l in err.strip().splitlines() if l and not l.startswith("BLOCKED_ATTEMPTS")][-1:] or [""]
    return {"code": r.returncode, "stdout": r.stdout.replace(str(tmp), "T"), "err_last": last[0].replace(str(tmp), "T")[:160], "attempts": attempts}
out = {}
cwd = tmp / "cwd"; cwd.mkdir()
sentinel = tmp / "sentinel.txt"; sentinel.write_text("s")
def seed(rr):
    for d, cnt in (("2026-04-08", 3), ("2026-04-09", 2), ("2026-04-10", 4)):
        put(rr / "evaluation/agent_effectiveness" / d / "agent_effectiveness_scorecard.json", {"components": {"strategist": {"post_scanner_refresh": {"comparison_count": cnt}}}})
    put(rr / "evaluation/agent_effectiveness/2026-04-08/strategist_stage2_authority_review.json", {"schema_version": SCHEMA, "records": [{"decision_id": "d1", "v": "a"}, {"decision_id": "d2"}, {"decision_id": ""}, "junk"]})
    put(rr / "evaluation/agent_effectiveness/2026-04-09/strategist_stage2_authority_review.json", {"schema_version": SCHEMA, "records": [{"decision_id": "d1", "v": "b"}, {"decision_id": "d3"}]})
    # 2026-04-10: no shard json -> regenerated by the real Stage2 writer (empty data)
# ---- A: single day, explicit output dir, populated root
rrA = tmp / "A/reports"; seed(rrA); oA = tmp / "A/out"
rA = run("A", ["--start", "2026-04-08", "--end", "2026-04-08", "--reports-root", str(rrA), "--output-dir", str(oA)], cwd)
check(rA["code"] == 0 and rA["attempts"] == 0, rA)
resA = json.loads(rA["stdout"])
check(sorted(resA) == ["json_path", "markdown_path", "range", "strategist_stage2_authority_review"] and resA["range"]["start"] == "2026-04-08", sorted(resA))
check(files(oA) == ["agent_effectiveness_scorecard.json", "agent_effectiveness_scorecard.md", "strategist_stage2_authority_review.json", "strategist_stage2_authority_review.md", "strategist_stage2_effectiveness_deep_dive.json", "strategist_stage2_effectiveness_deep_dive.md"], files(oA))
out["A"] = {"code": rA["code"], "files": files(oA), "stage2_keys": sorted(resA["strategist_stage2_authority_review"])}
# ---- B: range sharded, default output dir (= <reports>/evaluation/agent_effectiveness/<end>)
rrB = tmp / "B/reports"; seed(rrB)
rB = run("B", ["--start", "2026-04-08", "--end", "2026-04-11", "--reports-root", str(rrB)], cwd)
check(rB["code"] == 0 and rB["attempts"] == 0, rB)
dB = rrB / "evaluation/agent_effectiveness/2026-04-11"  # end-day dir (CLI default output) ; end-day daily scorecard is overwritten by the CLI before Stage2 reads it
rev = json.loads((dB / "strategist_stage2_authority_review.json").read_text(encoding="utf-8"))
check(rev["aggregation"] == {"method": "exact_daily_shards_deduped_by_decision_id", "shard_days": ["2026-04-08", "2026-04-09", "2026-04-10"], "shard_count": 3, "deduplicated_record_count": 3}, rev["aggregation"])
check({r["decision_id"]: r.get("v") for r in rev["records"]} == {"d1": "b", "d2": None, "d3": None}, rev["records"])  # later day wins on duplicate id; blank id / non-dict dropped
out["B"] = {"code": rB["code"], "agg": rev["aggregation"], "files_end_dir": files(dB), "shard_0410_regenerated": files(rrB / "evaluation/agent_effectiveness/2026-04-10"), "shard_0408_untouched": json.loads((rrB / "evaluation/agent_effectiveness/2026-04-08/strategist_stage2_authority_review.json").read_text(encoding="utf-8"))["records"][0]["v"]}
# rerun: end-day dir now holds the cumulative review (carries "aggregation"), consumed as a shard of itself
snap1 = {f: (dB / f).read_bytes() for f in files(dB)}
rB2 = run("B2", ["--start", "2026-04-08", "--end", "2026-04-11", "--reports-root", str(rrB)], cwd); check(rB2["code"] == 0, rB2)
snap2 = {f: (dB / f).read_bytes() for f in files(dB)}
rev2 = json.loads(snap2["strategist_stage2_authority_review.json"])
out["B_rerun"] = {"code": rB2["code"], "records_same": rev2["records"] == rev["records"], "agg_same": rev2["aggregation"] == rev["aggregation"], "changed_files": sorted(f for f in snap1 if snap1[f] != snap2[f])}
# ---- C: single-day partial failure: 3rd stage2 output name is occupied by a directory
rrC = tmp / "C/reports"; seed(rrC); oC = tmp / "C/out"; (oC / "strategist_stage2_effectiveness_deep_dive.json").mkdir(parents=True)
rC = run("C", ["--start", "2026-04-08", "--end", "2026-04-08", "--reports-root", str(rrC), "--output-dir", str(oC)], cwd)
check(rC["code"] == 1 and rC["stdout"] == "" and "IsADirectoryError" in rC["err_last"] and rC["attempts"] == 0, rC)
fC = files(oC)
check(fC == ["agent_effectiveness_scorecard.json", "agent_effectiveness_scorecard.md", "strategist_stage2_authority_review.json", "strategist_stage2_authority_review.md"], fC)  # scorecard + first 2 stage2 files exist, deep-dive absent
out["C_partial"] = {"code": rC["code"], "stdout_empty": rC["stdout"] == "", "err": rC["err_last"].split(":")[0], "files": fC}
shutil.rmtree(oC / "strategist_stage2_effectiveness_deep_dive.json")
rC2 = run("C2", ["--start", "2026-04-08", "--end", "2026-04-08", "--reports-root", str(rrC), "--output-dir", str(oC)], cwd); check(rC2["code"] == 0 and len(files(oC)) == 6, rC2)
out["C_recover"] = {"code": rC2["code"], "files": len(files(oC))}
# ---- D: scorecard-writer failure first: Stage2 is NOT started
rrD = tmp / "D/reports"; seed(rrD); oD = tmp / "D/out"; (oD / "agent_effectiveness_scorecard.md").mkdir(parents=True)
rD = run("D", ["--start", "2026-04-08", "--end", "2026-04-08", "--reports-root", str(rrD), "--output-dir", str(oD)], cwd)
check(rD["code"] == 1 and "IsADirectoryError" in rD["err_last"], rD)
check(files(oD) == ["agent_effectiveness_scorecard.json"], files(oD))  # json written, md blocked, no stage2 files
out["D_scorecard_fail"] = {"code": rD["code"], "files": files(oD)}
# ---- E: range shard regeneration fails (04-10 shard path blocked by a directory) -> exit 1 after scorecard written
rrE = tmp / "E/reports"; seed(rrE); (rrE / "evaluation/agent_effectiveness/2026-04-10/strategist_stage2_authority_review.json").mkdir(parents=True)
rE = run("E", ["--start", "2026-04-08", "--end", "2026-04-11", "--reports-root", str(rrE)], cwd)
check(rE["code"] == 1 and "IsADirectoryError" in rE["err_last"], rE)
fE = files(rrE / "evaluation/agent_effectiveness/2026-04-11")
check("agent_effectiveness_scorecard.json" in fE and "agent_effectiveness_scorecard.md" in fE and "strategist_stage2_authority_review.md" not in fE, fE)
out["E_shard_fail"] = {"code": rE["code"], "end_dir_files": fE}
# ---- F: argv / exit paths
rF = {}
for name, argv in {"missing_end": ["--reports-root", str(tmp / "F/reports")], "bad_end": ["--end", "notadate", "--reports-root", str(tmp / "F/reports"), "--output-dir", str(tmp / "F/o1")],
                   "start_after_end": ["--start", "2026-04-10", "--end", "2026-04-08", "--reports-root", str(tmp / "F/reports"), "--output-dir", str(tmp / "F/o2")],
                   "end_with_time": ["--start", "2026-04-08T09:00", "--end", "2026-04-08T15:30", "--reports-root", str(tmp / "F/reports"), "--output-dir", str(tmp / "F/o3")],
                   "empty_root_default_start": ["--end", "2026-06-02", "--reports-root", str(tmp / "F/reports"), "--output-dir", str(tmp / "F/o4")]}.items():
    r = run(name, argv, cwd); rF[name] = {"code": r["code"], "err": r["err_last"].split(":")[0][:40], "attempts": r["attempts"]}
check(rF["missing_end"]["code"] == 2 and rF["bad_end"]["code"] == 1 and rF["end_with_time"]["code"] == 0 and rF["empty_root_default_start"]["code"] == 0 and all(v["attempts"] <= 0 for v in rF.values()), rF)
out["F_argv"] = rF
# ---- G: relative --output-dir / --reports-root resolve against cwd
cwdG = tmp / "G"; cwdG.mkdir()
rG = run("G", ["--start", "2026-04-08", "--end", "2026-04-08", "--reports-root", "rel_reports", "--output-dir", "rel_out"], cwdG)
check(rG["code"] == 0 and len(files(cwdG / "rel_out")) == 6, rG); out["G_relative"] = {"code": rG["code"], "files": len(files(cwdG / "rel_out")), "reports_root_created": (cwdG / "rel_reports").exists()}
# ---- global effect checks
check(files(cwd) == [] and sentinel.read_text() == "s", "cwd/sentinel polluted")
check(before_repo() == repo_before, "repo working tree changed")
out["repo_tree_unchanged"] = True; out["stdout_json_range_B"] = json.loads(rB["stdout"])["range"]
shutil.rmtree(tmp, ignore_errors=True)
print(json.dumps(out, sort_keys=True, ensure_ascii=False))
print("RF065_SCORECARD_STAGE2_CONTINUOUS_OK single=6files range_shards=3 dedup=3 partial_fail_exit=1(files_left=4) scorecard_fail_blocks_stage2=yes shard_fail_exit=1 argparse=2 rerun_idempotent_records=%s child_attempts=0 repo_tree_unchanged=yes debug=%s" % (out["B_rerun"]["records_same"], "off" if opt else "on"))
