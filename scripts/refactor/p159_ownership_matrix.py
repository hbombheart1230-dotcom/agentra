"""P1.5 ownership matrix generator / verifier (source-grounded, reproducible).

Everything is read from Git OBJECTS of one explicit, reachable commit (`--sha`), never from the working tree, so the
output is a pure function of (sha, this script). `--verify` regenerates at the SHA recorded in the committed JSON and
compares rows + summary; any difference fails.

    python scripts/refactor/p159_ownership_matrix.py --sha <commit> --write      # regenerate JSON + MD + overlay
    python scripts/refactor/p159_ownership_matrix.py --verify                    # prove the committed matrix

Classes (one per module): CANONICAL_OWNER, COMPAT_FACADE, SAFETY_LOCK, KEEP, UNKNOWN.
Independent FLAGS (never conflated):
  CONTRACT_CANDIDATE - at least one Owner function still returns a POSITIONAL tuple of more than 8 values
                       (a contract-quality observation; says nothing about the name).
  RENAME_CANDIDATE   - at least one Owner function name is mechanically generated by the extraction tool (taken from the
                       historical moved-segment ledgers and never renamed). It is a review prompt, not a defect claim.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MATRIX_JSON = "docs/refactor/p1_5_third_pass_t3_ownership_matrix.json"
MATRIX_MD = "docs/refactor/p1_5_third_pass_t3_ownership_matrix.md"
OVERLAY_DOC = "docs/refactor/P15_CANONICAL_TARGET_TREE_AND_REPORTER_ASIS_2026_10_13.md"
LEDGERS = (("second_pass", "docs/refactor/p1_5_second_pass_moved_segments_ledger.json"),
           ("t1", "docs/refactor/p1_5_third_pass_t1_moved_segments_ledger.json"),
           ("t2", "docs/refactor/p1_5_third_pass_t2_moved_segments_ledger.json"))
T3_LEDGER = "docs/refactor/p1_5_third_pass_t3_owner_contract_ledger.json"
T3_1_LEDGER = "docs/refactor/p1_5_third_pass_t3_1_owner_contract_ledger.json"  # absent at pre-T3.1 SHAs
SCOPE = ["libs/runtime/commander", "libs/runtime/strategist", "libs/runtime/scanner", "libs/runtime/monitor",
         "libs/runtime/monitor_exit", "libs/reporting/reporter_bundle_runtime_parts",
         "libs/reporting/trade_memory_projection_parts", "libs/reporting/trade_read_model_parts",
         "libs/reporting/trade_report/ai_facade_parts", "apps/operator_ui"]
FACADES = {
    "graphs/nodes/strategist_node.py": "Strategist graph node (LLM boundary + state writes)",
    "graphs/nodes/scanner_node.py": "Scanner graph node (canonical ranking + selected rank)",
    "graphs/nodes/monitor_node.py": "Monitor graph node (OrderIntent / cooldown / entry-exit order)",
    "graphs/commander_runtime.py": "Commander runtime (route/phase authority, runtime ownership)",
    "libs/runtime/exit_policy.py": "Exit policy trigger precedence",
    "libs/runtime/intraday_monitor_signals.py": "Intraday entry signal evaluation",
    "libs/reporting/trade_report_ai.py": "Reporter AI facade (ABI)",
    "libs/reporting/trade_report_markdown_clean.py": "Reporter Markdown facade (ABI)",
    "libs/reporting/trade_story_pipeline.py": "Reporter story pipeline facade (ABI)",
    "libs/reporting/live_execution_bundle_runner.py": "Reporter bundle runner effect coordinator",
    "libs/reporting/trade_memory_surface.py": "Reporter memory surface API",
    "libs/reporting/trade_read_model.py": "Reporter read-model API",
    "libs/reporting/trade_report_ai_deterministic.py": "Reporter deterministic fallback API",
    "libs/reporting/trade_report_ai_compact_input.py": "Reporter compact LLM input API",
}
IO_TOK = re.compile(r"\b(open\(|\.write_text\(|\.read_text\(|os\.environ|os\.getenv|\.mkdir\(|subprocess\.|datetime\.now|"
                    r"time\.time\(|requests\.|sqlite3\.|logging\.|\.unlink\(|shutil\.)")
PRODUCTION_PREFIXES = ("libs/", "graphs/", "apps/", "scripts/run_", "conftest.py", "sitecustomize.py")


def git(*args, cwd=REPO, check=True):
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and r.returncode:
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr.strip()[:300]}")
    return r.stdout


def _blob(sha, path):
    return git("show", f"{sha}:{path}").lstrip("﻿")


def _consumers(sha, dotted):
    pkg, _, leaf = dotted.rpartition(".")
    pat = r"\b" + re.escape(dotted) + r"\b|from " + re.escape(pkg) + r" import .*\b" + re.escape(leaf) + r"\b"
    out = git("grep", "-l", "-E", pat, sha, "--", "*.py", check=False)
    return sorted({ln.split(":", 1)[1] for ln in out.splitlines() if ":" in ln})


def generate(sha):
    full = git("rev-parse", "--verify", sha + "^{commit}").strip()
    ledgers = {tag: json.loads(_blob(full, p))["segments"] for tag, p in LEDGERS}
    t3 = json.loads(_blob(full, T3_LEDGER))
    ledger_files = [T3_LEDGER]
    if git("ls-tree", "--name-only", full, "--", T3_1_LEDGER, check=False).strip():
        t3_1 = json.loads(_blob(full, T3_1_LEDGER))
        t3 = {**t3, "changes": t3["changes"] + t3_1["changes"]}
        ledger_files.append(T3_1_LEDGER)
    converted = {(c["old_module"], c["old_function"]) for c in t3["changes"]}
    new_pairs = {(c["new_module"], c["new_function"]) for c in t3["changes"]}
    renamed_old = {(c["old_module"], c["old_function"]) for c in t3["changes"] if c["old_function"] != c["new_function"]}
    led_by_owner = {}
    for tag, segs in ledgers.items():
        for s in segs:
            led_by_owner.setdefault(s["owner_module"], []).append((tag, s))
    tracked = [p for p in git("ls-tree", "-r", "--name-only", full).split("\n") if p.endswith(".py")]
    paths = sorted(p for p in tracked if any(p.startswith(s + "/") for s in SCOPE) or p in FACADES)
    rows = []
    for path in paths:
        src = _blob(full, path)
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        doc = (ast.get_docstring(tree) or "").strip().split("\n")[0][:140]
        funcs = [n for n in tree.body if isinstance(n, ast.FunctionDef)]
        defined = {f.name for f in funcs}
        dotted = path[:-3].replace("/", ".")
        consumers = [c for c in _consumers(full, dotted) if c != path]
        prod = [c for c in consumers if not c.startswith("tests/")]
        tests = [c for c in consumers if c.startswith("tests/")]
        entries = led_by_owner.get(path, [])
        unconverted = [s for _t, s in entries if (s["owner_module"], s["owner_function"]) not in converted
                       and s["owner_function"] in defined]
        max_arity = max([len(s["outputs"]) for s in unconverted] or [0])
        named_records = sum(1 for m, f in new_pairs if m == path and f in defined)
        generated = sorted({s["owner_function"] for t, s in entries
                            if t in ("second_pass", "t1") and s["owner_function"] in defined
                            and (s["owner_module"], s["owner_function"]) not in renamed_old})
        flags = []
        if max_arity > 8:
            flags.append("CONTRACT_CANDIDATE")
        if generated:
            flags.append("RENAME_CANDIDATE")
        if path in FACADES:
            cls, role = "COMPAT_FACADE", FACADES[path]
            action = "KEEP (public ABI / effect owner); delegates cohesive pure projections to Owners"
            if path.endswith("live_execution_bundle_runner.py"):
                cls, action = "SAFETY_LOCK", "KEEP effect coordinator; only PURE segments may leave (T2 done)"
        elif entries or named_records:
            tags = ",".join(sorted({t for t, _ in entries})) or "t3 split"
            cls, role, action = "CANONICAL_OWNER", f"extracted Owner ({tags})", "KEEP"
            if named_records:
                role += f"; {named_records} function(s) return named records (T3)"
            if "CONTRACT_CANDIDATE" in flags:
                action = "KEEP; named-record candidate (positional arity %d)" % max_arity
        elif path.endswith("__init__.py"):
            cls, role, action = "KEEP", "package marker", "KEEP"
        elif path.startswith("apps/operator_ui/"):
            base = os.path.basename(path)
            if base == "data_access_core.py":
                cls, role, action = ("COMPAT_FACADE", "Operator UI data-access coordinator (contains LLM brief path)",
                                     "KEEP; _load_operator_brief SAFETY_LOCK")
            elif base.startswith("data_access_brief"):
                cls, role, action = "CANONICAL_OWNER", "Operator brief read-model/render owner", "KEEP"
            else:
                cls, role, action = "KEEP", "Operator UI module", "KEEP"
        else:
            cls, role, action = "CANONICAL_OWNER", "pre-existing responsibility-named Owner (Wave A-C)", "KEEP"
        if not consumers and cls == "CANONICAL_OWNER" and not entries:
            cls, action = "UNKNOWN", "no static consumer found: reachability proof required before any action"
        rows.append({
            "module": path, "class": cls, "flags": flags, "role": role, "responsibility": doc or "(no module docstring)",
            "loc": src.count("\n") + 1, "public_functions": sum(1 for f in funcs if not f.name.startswith("_")),
            "functions": len(funcs), "prod_consumers": len(prod), "prod_consumer_sample": prod[:4],
            "test_consumers": len(tests), "max_unconverted_output_arity": max_arity, "named_record_functions": named_records,
            "generated_name_functions": len(generated),
            "facade_symbols": len(set(re.findall(r"\bfacade\.([A-Za-z_][A-Za-z0-9_]*)", src))),
            "side_effect_tokens": sorted({m.group(1).strip("(.") for m in IO_TOK.finditer(src)}), "action": action})
    summary = {"classes": {}, "flags": {}}
    for r in rows:
        summary["classes"][r["class"]] = summary["classes"].get(r["class"], 0) + 1
        for fl in r["flags"]:
            summary["flags"][fl] = summary["flags"].get(fl, 0) + 1
    return {"source_sha": full, "rows": rows, "summary": summary, "ledger_inputs": [p for _t, p in LEDGERS] + ledger_files}


def tree_delta(source_sha, head="HEAD"):
    names = [n for n in git("diff", "--name-only", source_sha, head).split("\n") if n]
    return {"from": source_sha, "to": git("rev-parse", head).strip(),
            "production_paths_changed": [n for n in names if n.endswith(".py") and n.startswith(PRODUCTION_PREFIXES)],
            "other_paths_changed": [n for n in names if not (n.endswith(".py") and n.startswith(PRODUCTION_PREFIXES))]}


def _script_sha():
    with open(os.path.abspath(__file__), "rb") as fh:
        return hashlib.sha256(fh.read().replace(b"\r\n", b"\n")).hexdigest()


def render_md(data):
    rows, s = data["rows"], data["summary"]
    by_pkg = {}
    for r in rows:
        by_pkg.setdefault(os.path.dirname(r["module"]), []).append(r)
    L = ["# P1.5 Third Pass T3 - ownership matrix (source-grounded, reproducible)", "",
         f"Source commit (reachable, immutable): `{data['source_sha']}`. Machine-readable: "
         "[p1_5_third_pass_t3_ownership_matrix.json](p1_5_third_pass_t3_ownership_matrix.json). Regenerate / prove:", "",
         f"    python scripts/refactor/p159_ownership_matrix.py --sha {data['source_sha']} --write",
         "    python scripts/refactor/p159_ownership_matrix.py --verify", "",
         f"Classes: {s['classes']}. Flags (independent): {s['flags']}. `CONTRACT_CANDIDATE` = unconverted positional "
         "return > 8 values; `RENAME_CANDIDATE` = mechanically generated Owner function name awaiting review. Neither "
         "flag is a claim that a name or contract is defective.", "",
         "## Summary by package", "",
         "| Package | modules | CANONICAL_OWNER | COMPAT_FACADE | CONTRACT_CANDIDATE | RENAME_CANDIDATE | max arity | LOC |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for pkg, rs in sorted(by_pkg.items()):
        L.append("| `%s` | %d | %d | %d | %d | %d | %d | %d |" % (
            pkg, len(rs), sum(r["class"] == "CANONICAL_OWNER" for r in rs), sum(r["class"] == "COMPAT_FACADE" for r in rs),
            sum("CONTRACT_CANDIDATE" in r["flags"] for r in rs), sum("RENAME_CANDIDATE" in r["flags"] for r in rs),
            max(r["max_unconverted_output_arity"] for r in rs), sum(r["loc"] for r in rs)))
    L += ["", "## Public facades / effect coordinators", "", "| Module | Class | Role | LOC | prod consumers | tests |",
          "|---|---|---|---:|---:|---:|"]
    for r in rows:
        if r["class"] in ("COMPAT_FACADE", "SAFETY_LOCK"):
            L.append("| `%s` | %s | %s | %d | %d | %d |" % (r["module"], r["class"], r["role"], r["loc"],
                                                          r["prod_consumers"], r["test_consumers"]))
    hot = sorted([r for r in rows if "CONTRACT_CANDIDATE" in r["flags"]],
                 key=lambda r: -r["max_unconverted_output_arity"])[:15]
    L += ["", "## Highest remaining positional-contract hotspots (CONTRACT_CANDIDATE)", "",
          "| Module | max arity | facade symbols | LOC | prod consumers | tests |", "|---|---:|---:|---:|---:|---:|"]
    for r in hot:
        L.append("| `%s` | %d | %d | %d | %d | %d |" % (r["module"], r["max_unconverted_output_arity"], r["facade_symbols"],
                                                      r["loc"], r["prod_consumers"], r["test_consumers"]))
    return "\n".join(L) + "\n"


def render_overlay(data):
    sha = data["source_sha"]
    tracked = {r["module"] for r in data["rows"]}
    all_tracked = [p for p in git("ls-tree", "-r", "--name-only", sha).split("\n") if p.endswith(".py")]
    doc_text = _blob(sha, OVERLAY_DOC)
    cut = doc_text.find("## G. Current status overlay")
    hist = doc_text if cut < 0 else doc_text[:cut]
    seen, rows = set(), []
    for line in hist.split("\n"):
        if "[P]" not in line:
            continue
        for tok in re.findall(r"([A-Za-z0-9_./-]+\.py)", line):
            tok = tok.strip("/")
            if not tok or tok.startswith(".") or tok.endswith("__init__.py") or tok in seen:
                continue
            seen.add(tok)
            hits = [t for t in all_tracked if t.endswith("/" + tok) or t == tok]
            decision = ("[E] promote marker" if hits else
                        "[P] keep planned; do NOT create without a genuine responsibility and consumer evidence")
            if tok.endswith("data_access_brief_text_rules.py") and not hits:
                decision = "[P] not created: no genuine responsibility proven"
            rows.append(f"| `{tok}` | {'EXISTS' if hits else 'NOT PRESENT'} | {hits[0] if hits else '-'} | {decision} |")
    pk = [("libs/reporting/reporter_bundle_runtime_parts/", "T2 bundle-runner pure projections"),
          ("libs/reporting/trade_memory_projection_parts/", "T1 memory surface projections"),
          ("libs/reporting/trade_read_model_parts/", "T1 read-model projections"),
          ("libs/reporting/trade_report/ai_facade_parts/", "T1 fallback / compact-input projections (fallback_*, compact_input_*)")]
    pkg_lines = [f"- `{p}` - {d}: {'EXISTS' if any(t.startswith(p) for t in all_tracked) else 'NOT PRESENT'}" for p, d in pk]
    ranking = [t for t in all_tracked if t.endswith("scanner/ranking_core.py")]
    sec = f"""## G. Current status overlay (verified against Git commit `{sha}`)

*The sections above are a historical design snapshot and are intentionally not rewritten. This overlay describes
exactly one immutable tree - commit `{sha}` - and is reproducible with `scripts/refactor/p159_ownership_matrix.py`.
Code that changed after that commit is recorded as a separate tree delta in the matrix JSON (`tree_delta`), never
folded silently into this snapshot.* Matrix: [p1_5_third_pass_t3_ownership_matrix.json](p1_5_third_pass_t3_ownership_matrix.json)
({len(data['rows'])} modules; classes {data['summary']['classes']}; flags {data['summary']['flags']}).

### G.1 Packages at that commit
{chr(10).join(pkg_lines)}

### G.2 Every `[P]` marker above, checked against that tree
| Planned path | Actual | Match | Decision |
|---|---|---|---|
{chr(10).join(rows)}

Explicit decisions: `libs/runtime/scanner/ranking_core.py` is **{'PRESENT' if ranking else 'NOT PRESENT and REJECTED'}** (a second canonical ranking authority must not be created; ranking stays in `scanner_node`); `apps/operator_ui/data_access_brief_text_rules.py` is created only if a genuine responsibility is proven.

### G.3 Locked / protected: [L]
`graphs/trading_graph.py`, legacy `libs/agent/*`, Reporter facades `trade_report_ai.py` / `trade_report_markdown_clean.py` / `trade_story_pipeline.py`, numbered `bodies_*.py`, `execute_from_packet.py`, `live_execution_bundle_runner.py::main` effect coordinator, `controlled_mock_lanes/`.

### G.4 Recommended tree (responsibility-based; no file is created for an old marker alone)
~~~
libs/runtime/{{commander,strategist,scanner,monitor,monitor_exit}}/   [E] keep; review mechanically generated names (RENAME_CANDIDATE flag) only after consumer mapping
libs/reporting/
  reporter_bundle_runtime_parts/   [E] targeted rows | exit/monitor context | human summaries | evidence+enrichment | closed-sell reconciliation | generation policy
  trade_memory_projection_parts/   [E] memory input + visibility | feedback rebuild | status summary | payload
  trade_read_model_parts/          [E] artifact selection | truth projection | display context
  trade_report/ai_facade_parts/    [E] fallback seed/summary/sections | compact input facts/payload
apps/operator_ui/                  [E] data_access_core (coordinator, LLM path SAFETY_LOCK) + data_access_brief_* owners
~~~
Reasoning: each unit has one read/projection responsibility and no I/O capability; folders exist only where a cohesive group of at least two Owners already lives.
"""
    return hist.rstrip("\n") + "\n\n" + sec


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sha")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args(argv)
    if a.verify:
        committed = json.loads(open(os.path.join(REPO, MATRIX_JSON), encoding="utf-8").read())
        fresh = generate(committed["source_sha"])
        ok = fresh["rows"] == committed["rows"] and fresh["summary"] == committed["summary"]
        print("VERIFY", "PASS" if ok else "FAIL", committed["source_sha"], len(fresh["rows"]), "rows")
        if not ok:
            a_rows = {r["module"]: r for r in committed["rows"]}
            for r in fresh["rows"]:
                if a_rows.get(r["module"]) != r:
                    print("  differs:", r["module"])
        return 0 if ok else 1
    if not a.sha:
        ap.error("--sha is required unless --verify")
    data = generate(a.sha)
    if a.write:
        data["generator"] = {"script": "scripts/refactor/p159_ownership_matrix.py", "script_sha256": _script_sha(),
                             "command": f"python scripts/refactor/p159_ownership_matrix.py --sha {data['source_sha']} --write",
                             "verify": "python scripts/refactor/p159_ownership_matrix.py --verify"}
        data["tree_delta"] = tree_delta(data["source_sha"])
        data["schema"] = "p159_t3_ownership_matrix.v2"
        order = {k: data[k] for k in ("schema", "source_sha", "generator", "summary", "tree_delta", "ledger_inputs", "rows")}
        open(os.path.join(REPO, MATRIX_JSON), "w", encoding="utf-8", newline="\n").write(
            json.dumps(order, indent=1, ensure_ascii=False))
        open(os.path.join(REPO, MATRIX_MD), "w", encoding="utf-8", newline="\n").write(render_md(data))
        open(os.path.join(REPO, OVERLAY_DOC), "w", encoding="utf-8", newline="\n").write(render_overlay(data))
        print("written", len(data["rows"]), data["summary"], "delta:", len(order["tree_delta"]["production_paths_changed"]))
    else:
        print(json.dumps({"source_sha": data["source_sha"], "rows": len(data["rows"]), "summary": data["summary"]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
