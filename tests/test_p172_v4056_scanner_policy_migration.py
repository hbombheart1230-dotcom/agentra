def test_facade_late_binding_survives_the_move(monkeypatch):
    node = importlib.import_module("graphs.nodes.scanner_node")
    model = {"avg_pnl_pct": 4.0, "win_rate": 0.8, "trade_count": 12, "dominant_playbook": "breakout"}
    before = node._compute_symbol_prior_adjustment(symbol_model=model, playbook="breakout", current_day="2026-10-16")
    monkeypatch.setattr(node, "_clamp", lambda value, lower=0.0, upper=1.0: 0.123456)
    after = node._compute_symbol_prior_adjustment(symbol_model=model, playbook="breakout", current_day="2026-10-16")
    assert after != before


